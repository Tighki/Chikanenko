async function main() {
  if (!fs.existsSync(xlsxPath)) {
    console.error("Установите зависимости в Chikanenko-Back (npm install) или добавьте xlsx в PATH.");
    process.exit(1);
  }
  const XLSX = await import(pathToFileURL(xlsxPath).href);
  fs.mkdirSync(outDir, { recursive: true });
  fs.mkdirSync(publicDir, { recursive: true });

  for (const file of files) {
    const sheet = XLSX.utils.aoa_to_sheet([headers, ...file.rows]);
    const book = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(book, sheet, file.sheet);
    const buffer = XLSX.write(book, { type: "buffer", bookType: "xlsx" });
    for (const dir of [outDir, publicDir]) {
      const target = path.join(dir, file.name);
      fs.writeFileSync(target, buffer);
      console.log("Wrote", target, `(${file.rows.length} students)`);
    }
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
